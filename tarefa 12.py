#12.  O  Cofre  Persistente:  Crie  uma  senha  secreta  (ex:  "dragao123").  Use  um  laço 
#while que  peça  a  senha  ao  usuário  repetidamente.  Enquanto  ele  errar,  mostre 
#"Senha incorreta, tente novamente!". Quando acertar, encerre o loop e mostre 
# "Cofre Aberto!". 
senha = input("Digite a sua senha:")
while senha !="dragao123":
    print("senha incorreta, tente novamente!")
    senha = input("Digite sua senha:")
print("Confre aberto!")

